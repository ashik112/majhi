// Writes src/features/map/logos.generated.ts from the pinned `simple-icons` package (MIT, CC0 icon data).
// Run: node apps/web/scripts/gen-logos.mjs   (only when this list or the package version changes)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const icons = require("simple-icons");
const version = JSON.parse(
  readFileSync(new URL("../node_modules/simple-icons/package.json", import.meta.url), "utf8"),
).version;

